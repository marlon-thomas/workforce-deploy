#!/usr/bin/env python3
"""images-lock.py - every image the appliance controller may run, pinned by digest (Workforce ADR-0032 §5).

The controller's allow-list proxy refuses a pull, or a container, of any image that isn't on this list, a signed
release manifest's, or its own. It is everything the controller's Compose file runs (compose.yaml with
compose.controller.yaml, every profile the controller can switch on) and every helper the scripts start
(`*_IMAGE="…@sha256:…"` in bin/). The Workforce images come from the signed release manifest instead, so they
are not here. bin/ci-validate.sh fails when images.lock is not what this prints.

    python3 -I bin/images-lock.py controller.json > images.lock
"""
import glob
import json
import re
import sys

PIN = re.compile(r"^[a-z0-9][a-z0-9._/:-]*@sha256:[0-9a-f]{64}$")
SCRIPT_PIN = re.compile(r'^\s*[A-Z_]*IMAGE="([^"$]+@sha256:[0-9a-f]{64})"', re.M)


def main(path):
    with open(path, encoding="utf-8") as f:
        config = json.load(f)
    images, problems = set(), []
    for svc, s in sorted((config.get("services") or {}).items()):
        image = s.get("image", "")
        if image.startswith("ghcr.io/ci/"):  # the placeholder for the Workforce images: from the signed manifest
            continue
        if PIN.match(image):
            images.add(image)
        else:
            problems.append(f"{svc}: {image} is not pinned by digest")
    for script in sorted(glob.glob("bin/*.sh") + glob.glob("bin/lib/*.sh")):
        with open(script, encoding="utf-8") as f:
            for image in SCRIPT_PIN.findall(f.read()):
                images.add(image)
    for p in problems:
        print(f"FAIL {p}", file=sys.stderr)
    if problems:
        return 1
    print("# Every image the appliance controller may run, pinned by digest: generated by bin/images-lock.py from")
    print("# compose.yaml + compose.controller.yaml and the helpers the scripts start. Do not edit by hand.")
    for image in sorted(images):
        print(image)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
